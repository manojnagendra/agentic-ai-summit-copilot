export function sessionById(id: string): Session | undefined {
  return SESSIONS.find((s) => s.id === id)
}

export function sessionsForDay(day: Session['day']): Session[] {
  return SESSIONS.filter((s) => s.day === day).sort((a, b) => a.start.localeCompare(b.start))
}
